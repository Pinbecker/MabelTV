import { test, expect } from './test-fixtures.mjs'
import { openStudio } from './studio-fixtures.mjs'
test.use({serviceWorkers:'block'})
test('Studio uses the existing film sheet and settings actions with native selects', async ({page}, info) => {
 const errors=[]; page.on('pageerror',error=>errors.push(error.message))
 await page.addInitScript(()=>{localStorage.setItem('mabeltv-experience-theme','light');localStorage.setItem('mabeltv-experience-accent-hue','180')})
 const {writes}=await openStudio(page)
 const historyLength=await page.evaluate(()=>history.length)
 await page.getByRole('button',{name:'Arrival',exact:true}).click()
 await expect(page.locator('#studioDestinationSheet')).toBeVisible()
 await expect(page.locator('#studioDestinationMore')).toHaveClass(/card-settings-trigger/)
 await expect(page.locator('#studioCompression')).toBeVisible()
 await page.locator('#studioCompression').selectOption('balanced')
 await expect(page.locator('#studioCompression')).toHaveValue('balanced')
 await expect(page.locator('#studioOptionSheet,.studio-select-trigger,#studioCloudCollection,#studioCompressionEstimate')).toHaveCount(0)
 await expect(page.locator('#studioDestinationSubmit')).toHaveText('Send to My TV')
 const copyGap=await page.locator('#studioCloudCopiesField').evaluate(node=>node.getBoundingClientRect().top-document.querySelector('#studioCompressionField').getBoundingClientRect().bottom)
 expect(copyGap).toBeGreaterThanOrEqual(15)
 await page.screenshot({path:info.outputPath('send-light.png'),animations:'disabled'})
 await page.locator('#studioDestinationMore').click()
 await expect(page.locator('#studioActionsSheet .my-tv-film-settings-actions')).toBeVisible()
 await expect(page.locator('#studioCloudMoveCollection')).toHaveCount(0)
 const settings = await page.locator('#studioActionsSheet > article').boundingBox()
 expect(settings.height).toBeLessThan(page.viewportSize().height * .7)
 await page.screenshot({path:info.outputPath('settings-light.png'),animations:'disabled'})
 await page.locator('#studioCloudOptimise').click()
 await expect(page.locator('#studioOptimiseConfirm')).toBeEnabled()
 await expect(page.locator('#studioOptimiseCompression')).toBeVisible()
 const gap=await page.locator('.studio-optimise-comparison').evaluate(node=>node.getBoundingClientRect().top-node.previousElementSibling.getBoundingClientRect().bottom)
 expect(gap).toBeGreaterThanOrEqual(15)
 await expect(page.locator('#studioOptimiseOutput')).toHaveCount(0)
 await page.screenshot({path:info.outputPath('optimise-light.png'),animations:'disabled'})
 await page.locator('#studioOptimiseCancel').click()
 await page.locator('#studioActionsClose').click()
 await page.locator('#studioTargetCollection').selectOption('__new__')
 await page.locator('#studioNewCollectionName').fill('Favourites')
 await page.locator('#studioCreateCollection').click()
 await expect(page.locator('#studioTargetCollection')).toHaveValue('Favourites')
 expect(writes.find(w=>w.path==='/api/studio/collections')).toMatchObject({scope:'pi'})
 await page.evaluate(()=>window.MabelExperienceTheme.set('dark'))
 await page.screenshot({path:info.outputPath('send-dark.png'),animations:'disabled'})
 await page.locator('#studioDestinationMore').click()
 await page.keyboard.press('Escape')
 await expect(page.locator('#studioDestinationSheet')).toBeVisible()
 await page.locator('#studioDestinationMore').click()
 await page.mouse.click(2,2)
 await expect(page.locator('#studioDestinationSheet')).toBeVisible()
 await page.locator('#studioDestinationClose').click()
 await expect(page.locator('dialog[open]')).toHaveCount(0)
 expect(await page.evaluate(()=>history.length)).toBe(historyLength)
 expect(errors).toEqual([])
})
